"""Build lyrics/lyrics.src.js: the lyric sheet in this recording's structure,
with approximate line times taken from the Whisper transcript.

The supplied sheet had two choruses and line times ~3 s apart; this recording
sings the lines ~1.8 s apart and has four choruses (two after the instrumental
break). The words come from the sheet (Whisper mishears some of them); only the
timing comes from Whisper, by matching the sheet's words to Whisper's words.
The supplied sheet read "Lieb nicht wie ich wär" / "Lieb nicht weil du musst"; this
recording sings "Lieb mich" there (Whisper hears it and it aligns better in all eight
places, see align.py VARIANTS), so the sheet below follows the recording.

Run:  uv run python sheet.py   (after transcribe.py)
"""
import common
