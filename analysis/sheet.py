STRUCTURE = [VERSE1, CHORUS, VERSE2, CHORUS, CHORUS, CHORUS]


def key(w):
    return re.sub(r"[^a-zäöüß]", "", w.lower())


def align_words(a, b):
    """Global in-order alignment (edit distance) of two word lists; returns the
    (i, j) pairs of equal or near-equal words. Unlike difflib it cannot pin a
    repeated chorus to the wrong repeat."""
    sim = lambda x, y: difflib.SequenceMatcher(a=x, b=y).ratio()
    n, m = len(a), len(b)
    INF = float("inf")
    D = [[INF] * (m + 1) for _ in range(n + 1)]
    D[0] = [float(j) for j in range(m + 1)]
    for i in range(1, n + 1):
        D[i][0] = float(i)
        for j in range(1, m + 1):
            c = 1.0 - sim(a[i - 1], b[j - 1])
            D[i][j] = min(D[i - 1][j - 1] + 2 * c, D[i - 1][j] + 1, D[i][j - 1] + 1)
    pairs, i, j = [], n, m
    while i and j:
        c = 1.0 - sim(a[i - 1], b[j - 1])
        if D[i][j] == D[i - 1][j - 1] + 2 * c:
            if c < 0.5:
                pairs.append((i - 1, j - 1))
            i, j = i - 1, j - 1
        elif D[i][j] == D[i - 1][j] + 1:
            i -= 1
        else:
            j -= 1
    return pairs[::-1]


def main():
    lines = [l for block in STRUCTURE for l in block.splitlines()]
    sheet = [(li, w) for li, l in enumerate(lines) for w in l.split()]
    wh = [w for s in json.loads((common.WORK / "whisper.json").read_text()) for w in s["words"]]
    t_of = {}  # sheet word index -> (start, end)
    for a, b in align_words([key(w) for _, w in sheet], [key(w["w"]) for w in wh]):
        t_of[a] = (wh[b]["start"], wh[b]["end"])
    out = []
    for li, text in enumerate(lines):
        idx = [k for k, (l, _) in enumerate(sheet) if l == li]
        hit = [t_of[k] for k in idx if k in t_of]
        if not hit:  # filled in from the neighbours below
            out.append([None, None, text, f"0/{len(idx)}"])
            continue
        out.append([round(min(h[0] for h in hit), 2), round(max(h[1] for h in hit), 2), text,
                    f"{len(hit)}/{len(idx)}"])
    for i, o in enumerate(out):
        if o[0] is None:
            o[0] = round(out[i - 1][1] + 0.05, 2)
            o[1] = round(next(x[0] for x in out[i + 1:] if x[0] is not None) - 0.05, 2)
    # a line with only some words matched can be short: extend it to the neighbours
    for i, o in enumerate(out):
        if o[3].split("/")[0] != o[3].split("/")[1]:
            lo = out[i - 1][1] if i else o[0] - 1.0
            hi = out[i + 1][0] if i + 1 < len(out) else o[1] + 1.0
            o[0], o[1] = round(min(o[0], lo + 0.05), 2), round(max(o[1], hi - 0.05), 2)
    body = ",\n".join("  " + json.dumps(o[:3], ensure_ascii=False) for o in out)
    common.LYRICS_SRC.write_text(
        "// Line-level lyrics with approximate timings: (start s, end s, text) per line.\n"
        "// Generated by analysis/sheet.py: words from the supplied lyric sheet in this\n"
        "// recording's structure (four choruses), times from the Whisper transcript.\n"
        f"export const LY = [\n{body}\n];\n", encoding="utf-8")
    for o in out:
        print(f"{o[0]:7.2f} {o[1]:7.2f}  {o[3]:>5}  {o[2]}")
    print(len(out), "lines ->", common.LYRICS_SRC)


if __name__ == "__main__":
    main()
